export type Appliance = "stove" | "oven" | "microwave" | "air fryer" | "toaster";
export type KitchenKind = "full" | "micro" | "dorm" | "barracks";
export type FridgeAccess = "full" | "mini" | "none";
export type MicrowaveAccess = "mine" | "shared" | "none";
export type MealType = "breakfast" | "lunch" | "dinner" | "snack";
export type Aisle =
  | "Produce"
  | "Meat & Deli"
  | "Dairy & Eggs"
  | "Bakery"
  | "Frozen"
  | "Pantry / Canned"
  | "Spices & Condiments";

export interface RecipeIngredient {
  name: string;
  /** Amount for 1 serving; null means "not scaled" and `unit` holds the full amount text. */
  qty: number | null;
  unit: string;
  aisle: Aisle;
  /** Matches the "what do you have" chips (e.g. "eggs", "rice"). */
  key: string;
  /** Round up to whole items (eggs, tortillas) instead of showing fractions. */
  whole?: boolean;
}

export interface Recipe {
  id: string;
  name: string;
  emoji: string;
  /** Background color slot 1–5 for the plate circle. */
  plate: number;
  mealType: MealType;
  minutes: number;
  lowEffort: boolean;
  classic: boolean;
  /** Counts as a classic when the user has no fridge ("Room classics"). */
  roomClassic?: boolean;
  /** Any one of these appliances works; empty means no cooking needed. */
  cook: Appliance[];
  /** 0 = no fridge needed, 1 = mini fridge, 2 = full fridge with freezer. */
  fridge: 0 | 1 | 2;
  description: string;
  rememberAs: string;
  ingredients: RecipeIngredient[];
  /** {n} is replaced with ingredient n's scaled amount. */
  steps: string[];
  lazyVersion?: string;
  /** True for ideas generated by AI. */
  generated?: boolean;
}

export interface KitchenSetup {
  kitchen: KitchenKind;
  /** Used when kitchen is "full". */
  appliances: Appliance[];
  /** Used for micro / dorm / barracks. */
  fridge: FridgeAccess;
  /** Used for dorm / barracks. */
  microwave: MicrowaveAccess;
  servings: number;
}

export interface GroceryEntry {
  recipeId: string;
  servings: number;
}
